describe("generateMigrationSQL (Postgres ALTER paths)", () => {
  const T = "tables[id=1,name=users]";
  const col = (extra) => `${T}#fields[id=10,name=age,type=INTEGER]${extra}`;
  const tbl = (id, name, fields = []) => ({ id, name, comment: "", inherits: [], uniqueConstraints: [], indices: [], fields });
  const fld = (o) => makeField(o);

  it("add column -> ADD COLUMN up / DROP COLUMN down", () => {
    const to = { tables: [tbl(1, "users", [fld({ id: 10, name: "age", type: "INTEGER", default: "0" })])] };
    const from = { tables: [tbl(1, "users", [])] };
    const { up, down } = generateMigrationSQL(
      { [col("")]: { to: to.tables[0].fields[0], from: null } },
      DB.POSTGRES,
      { from, to },
    );
    expect(up).toMatch(/ALTER TABLE "users" ADD COLUMN "age" INTEGER/);
    expect(down).toMatch(/ALTER TABLE "users" DROP COLUMN "age"/);
  });

  it("type change -> ALTER COLUMN ... TYPE", () => {
    const { up, down } = generateMigrationSQL(
      { [col("#type")]: { from: "INTEGER", to: "BIGINT" } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toContain('ALTER TABLE "users" ALTER COLUMN "age" TYPE BIGINT;');
    expect(down).toContain('ALTER TABLE "users" ALTER COLUMN "age" TYPE INTEGER;');
  });

  it("notNull -> SET/DROP NOT NULL", () => {
    const { up, down } = generateMigrationSQL(
      { [col("#notNull")]: { from: false, to: true } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toContain('SET NOT NULL');
    expect(down).toContain('DROP NOT NULL');
  });

  it("default -> SET DEFAULT / DROP DEFAULT", () => {
    const { up, down } = generateMigrationSQL(
      { [col("#default")]: { from: "", to: "0" } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toContain('ALTER TABLE "users" ALTER COLUMN "age" SET DEFAULT 0;');
    expect(down).toContain('DROP DEFAULT');
  });

  it("check -> ADD/DROP CONSTRAINT", () => {
    const { up, down } = generateMigrationSQL(
      { [col("#check")]: { from: "", to: "age > 0" } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toMatch(/ADD CONSTRAINT "users_age_check" CHECK \(age > 0\)/);
    expect(down).toMatch(/DROP CONSTRAINT "users_age_check"/);
  });

  it("increment -> ADD/DROP IDENTITY", () => {
    const { up, down } = generateMigrationSQL(
      { [col("#increment")]: { from: false, to: true } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toContain('ADD GENERATED BY DEFAULT AS IDENTITY');
    expect(down).toContain('DROP IDENTITY');
  });

  it("isArray -> TYPE ...[] USING", () => {
    const { up, down } = generateMigrationSQL(
      { [col("#isArray")]: { from: false, to: true } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toContain('TYPE INTEGER[] USING "age"::INTEGER[];');
    expect(down).toContain('USING "age"[1];');
  });

  it("size -> ALTER COLUMN ... TYPE type(size)", () => {
    const path = `${T}#fields[id=10,name=name,type=VARCHAR]#size`;
    const { up } = generateMigrationSQL(
      { [path]: { from: "50", to: "100" } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toContain('ALTER TABLE "users" ALTER COLUMN "name" TYPE VARCHAR(100);');
  });

  it("rename column -> RENAME COLUMN", () => {
    const { up, down } = generateMigrationSQL(
      { [col("#name")]: { from: "age", to: "years" } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toContain('RENAME COLUMN "age" TO "years";');
    expect(down).toContain('RENAME COLUMN "years" TO "age";');
  });

  it("unique -> ADD/DROP CONSTRAINT UNIQUE", () => {
    const { up } = generateMigrationSQL(
      { [col("#unique")]: { from: false, to: true } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toMatch(/ADD CONSTRAINT "users_age_unique" UNIQUE \("age"\)/);
  });

  it("primary -> ADD/DROP CONSTRAINT PRIMARY KEY", () => {
    const { up } = generateMigrationSQL(
      { [col("#primary")]: { from: false, to: true } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toMatch(/ADD CONSTRAINT "users_pkey" PRIMARY KEY \("age"\)/);
  });

  it("add foreign key relationship -> ADD CONSTRAINT ... FOREIGN KEY", () => {
    const to = {
      tables: [
        tbl("u", "u", [fld({ id: "u1", name: "id", primary: true })]),
        tbl("p", "p", [fld({ id: "p1", name: "uid" })]),
      ],
      relationships: [
        {
          id: "r1",
          name: "fk_p_u",
          startTableId: "p",
          endTableId: "u",
          fields: [{ startFieldId: "p1", endFieldId: "u1" }],
          updateConstraint: "Cascade",
          deleteConstraint: "No action",
        },
      ],
    };
    const { up, down } = generateMigrationSQL(
      { "relationships[id=r1]": { to: to.relationships[0], from: null } },
      DB.POSTGRES,
      { from: { tables: to.tables, relationships: [] }, to },
    );
    expect(up).toMatch(/ALTER TABLE "p" ADD CONSTRAINT "fk_p_u" FOREIGN KEY \("uid"\) REFERENCES "u" \("id"\)/);
    expect(up).toContain("ON UPDATE CASCADE ON DELETE NO ACTION");
    expect(down).toMatch(/ALTER TABLE "p" DROP CONSTRAINT "fk_p_u"/);
  });

  it("add enum -> CREATE TYPE AS ENUM / DROP TYPE", () => {
    const e = { name: "mood", values: ["happy", "sad"] };
    const { up, down } = generateMigrationSQL(
      { "enums[id=0,name=mood]": { to: e, from: null } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toContain('CREATE TYPE "mood" AS ENUM');
    expect(down).toContain('DROP TYPE "mood";');
  });

  it("add composite type -> CREATE TYPE AS (...)", () => {
    const ty = { name: "addr", comment: "", fields: [{ name: "street", type: "TEXT" }] };
    const { up } = generateMigrationSQL(
      { "types[id=0,name=addr]": { to: ty, from: null } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toContain('CREATE TYPE "addr" AS (');
    expect(up).toContain('"street" TEXT');
  });

  it("inherits -> INHERIT / NO INHERIT", () => {
    const { up, down } = generateMigrationSQL(
      { "tables[id=1,name=child]#inherits#0": { from: null, to: "parent" } },
      DB.POSTGRES,
      { from: {}, to: {} },
    );
    expect(up).toContain('ALTER TABLE "child" INHERIT "parent";');
    expect(down).toContain('ALTER TABLE "child" NO INHERIT "parent";');
  });
});

