describe("dbToTypes[POSTGRES] checkDefault", () => {
  const pg = dbToTypes[DB.POSTGRES];
  const ok = (type, def, size) => pg[type].checkDefault({ default: def, size });

  it("INTEGER accepts integers, rejects decimals", () => {
    expect(ok("INTEGER", "5")).toBe(true);
    expect(ok("INTEGER", "-3")).toBe(true);
    expect(ok("INTEGER", "5.5")).toBe(false);
    expect(ok("INTEGER", "abc")).toBe(false);
  });

  it("NUMERIC accepts decimals", () => {
    expect(ok("NUMERIC", "5.5")).toBe(true);
    expect(ok("NUMERIC", "10")).toBe(true);
    expect(ok("NUMERIC", "abc")).toBe(false);
  });

  it("VARCHAR honours the size budget (quoted and unquoted)", () => {
    expect(ok("VARCHAR", "'active'", 10)).toBe(true);
    expect(ok("VARCHAR", "toolongvalue", 5)).toBe(false);
    expect(ok("VARCHAR", "'toolongvalue'", 5)).toBe(false);
  });

  it("CHAR honours the size budget", () => {
    expect(ok("CHAR", "'a'", 1)).toBe(true);
    expect(ok("CHAR", "ab", 1)).toBe(false);
  });

  it("BOOLEAN accepts true/false only", () => {
    expect(ok("BOOLEAN", "true")).toBe(true);
    expect(ok("BOOLEAN", "FALSE")).toBe(true);
    expect(ok("BOOLEAN", "1")).toBe(false);
  });

  it("UUID validates the canonical form", () => {
    expect(ok("UUID", "123e4567-e89b-12d3-a456-426614174000")).toBe(true);
    expect(ok("UUID", "not-a-uuid")).toBe(false);
  });

  it("DATE accepts ISO dates and special values", () => {
    expect(ok("DATE", "2020-01-01")).toBe(true);
    expect(ok("DATE", "now")).toBe(true);
    expect(ok("DATE", "nonsense")).toBe(false);
  });

  it("TIMESTAMP accepts a full timestamp and current_timestamp", () => {
    expect(ok("TIMESTAMP", "2020-01-01 00:00:00")).toBe(true);
    expect(ok("TIMESTAMP", "current_timestamp")).toBe(true);
  });

  it("BIT accepts a bitstring", () => {
    expect(ok("BIT", "1010")).toBe(true);
    expect(ok("BIT", "12")).toBe(false);
  });

  it("JSON accepts anything (no default validation)", () => {
    expect(ok("JSON", '{"a":1}')).toBe(true);
  });

  // FLAG (data/datatypes.js, shared/forbidden to edit): the TIMESTAMP validator
  // has an OR-branch that accepts anything whose leading YYYY is 1970..2038, so
  // a garbage value like "1999-13-45 99:99:99" passes. Documented, not fixed.
  it.fails("TIMESTAMP should reject an impossible date (catalog looseness)", () => {
    expect(ok("TIMESTAMP", "1999-13-45 99:99:99")).toBe(false);
  });
});

