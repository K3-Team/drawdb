describe("toPostgres export clauses", () => {
  it("quotes identifiers and emits IF NOT EXISTS", () => {
    const sql = toPostgres(
      makeDiagram({
        tables: [
          makeTable({ name: "users", fields: [makeField({ name: "id" })] }),
        ],
      }),
    );
    expect(sql).toContain('CREATE TABLE IF NOT EXISTS "users"');
    expect(sql).toContain('"id"');
  });

  it("NOT NULL, UNIQUE, DEFAULT and CHECK clauses", () => {
    const sql = toPostgres(
      makeDiagram({
        tables: [
          makeTable({
            name: "t",
            fields: [
              makeField({ name: "email", type: "VARCHAR", size: 255, notNull: true, unique: true }),
              makeField({ name: "status", type: "VARCHAR", size: 20, default: "active" }),
              makeField({ name: "age", type: "INTEGER", check: "age >= 0" }),
            ],
          }),
        ],
      }),
    );
    expect(sql).toContain('"email" VARCHAR(255) NOT NULL UNIQUE');
    expect(sql).toContain(`"status" VARCHAR(20) DEFAULT 'active'`);
    expect(sql).toContain('"age" INTEGER CHECK(age >= 0)');
  });

  it("increment renders GENERATED BY DEFAULT AS IDENTITY", () => {
    const sql = toPostgres(
      makeDiagram({
        tables: [
          makeTable({
            name: "t",
            fields: [makeField({ name: "id", type: "INTEGER", increment: true, primary: true })],
          }),
        ],
      }),
    );
    expect(sql).toContain('"id" INTEGER GENERATED BY DEFAULT AS IDENTITY');
    expect(sql).toContain('PRIMARY KEY("id")');
  });

  it("array column renders the ARRAY keyword", () => {
    const sql = toPostgres(
      makeDiagram({
        tables: [
          makeTable({ name: "t", fields: [makeField({ name: "tags", type: "TEXT", isArray: true })] }),
        ],
      }),
    );
    expect(sql).toContain('"tags" TEXT ARRAY');
  });

  it("composite PRIMARY KEY", () => {
    const sql = toPostgres(
      makeDiagram({
        tables: [
          makeTable({
            name: "t",
            fields: [
              makeField({ name: "a", type: "INTEGER", primary: true }),
              makeField({ name: "b", type: "INTEGER", primary: true }),
            ],
          }),
        ],
      }),
    );
    expect(sql).toContain('PRIMARY KEY("a", "b")');
  });

  it("named UNIQUE constraint", () => {
    const sql = toPostgres(
      makeDiagram({
        tables: [
          makeTable({
            name: "t",
            fields: [makeField({ name: "slug", type: "VARCHAR", size: 100 })],
            uniqueConstraints: [{ id: 0, name: "uq_slug", fields: ["slug"] }],
          }),
        ],
      }),
    );
    expect(sql).toContain('CONSTRAINT "uq_slug" UNIQUE ("slug")');
  });

  it("table and column COMMENT ON statements", () => {
    const sql = toPostgres(
      makeDiagram({
        tables: [
          makeTable({
            name: "t",
            comment: "a table",
            fields: [makeField({ name: "id", comment: "the id" })],
          }),
        ],
      }),
    );
    expect(sql).toContain(`COMMENT ON TABLE "t" IS 'a table';`);
    expect(sql).toContain(`COMMENT ON COLUMN "t"."id" IS 'the id';`);
  });

  it("CREATE INDEX (plain and unique)", () => {
    const sql = toPostgres(
      makeDiagram({
        tables: [
          makeTable({
            name: "t",
            fields: [makeField({ name: "a" }), makeField({ name: "b" })],
            indices: [
              { id: 0, name: "idx_a", unique: false, fields: ["a"] },
              { id: 1, name: "uidx_b", unique: true, fields: ["b"] },
            ],
          }),
        ],
      }),
    );
    expect(sql).toContain('CREATE INDEX "idx_a"\nON "t" ("a");');
    expect(sql).toContain('CREATE UNIQUE INDEX "uidx_b"\nON "t" ("b");');
  });

  it("CREATE TYPE AS ENUM", () => {
    const sql = toPostgres(makeDiagram({ enums: [{ name: "mood", values: ["happy", "sad"] }] }));
    expect(sql).toContain('CREATE TYPE "mood" AS ENUM');
    expect(sql).toContain("'happy'");
    expect(sql).toContain("'sad'");
  });

  it("CREATE TYPE AS (composite) with a comment", () => {
    const sql = toPostgres(
      makeDiagram({
        types: [
          { name: "addr", comment: "an address", fields: [{ name: "street", type: "TEXT" }, { name: "zip", type: "INTEGER" }] },
        ],
      }),
    );
    expect(sql).toContain('CREATE TYPE "addr" AS (');
    expect(sql).toContain('"street" TEXT');
    expect(sql).toContain(`COMMENT ON TYPE "addr" IS 'an address';`);
  });

  it("INHERITS clause", () => {
    const sql = toPostgres(
      makeDiagram({
        tables: [
          makeTable({ name: "parent", fields: [makeField({ name: "id", primary: true })] }),
          makeTable({ name: "child", inherits: ["parent"], fields: [makeField({ name: "extra" })] }),
        ],
      }),
    );
    expect(sql).toContain(') INHERITS ("parent")');
  });

  it("foreign key ALTER TABLE with ON UPDATE / ON DELETE", () => {
    const uid = fid();
    const rid = fid();
    const sql = toPostgres(
      makeDiagram({
        tables: [
          makeTable({ id: "u", name: "u", fields: [makeField({ id: uid, name: "id", primary: true })] }),
          makeTable({ id: "p", name: "p", fields: [makeField({ id: rid, name: "uid" })] }),
        ],
        references: [
          {
            id: "r1",
            name: "fk",
            startTableId: "p",
            endTableId: "u",
            startFieldId: rid,
            endFieldId: uid,
            fields: [{ startFieldId: rid, endFieldId: uid }],
            updateConstraint: "Cascade",
            deleteConstraint: "Set null",
          },
        ],
      }),
    );
    expect(sql).toContain('ALTER TABLE "p"');
    expect(sql).toContain('ADD FOREIGN KEY("uid") REFERENCES "u"("id")');
    expect(sql).toContain("ON UPDATE CASCADE ON DELETE SET NULL");
  });
});

