// ---- fixture builders -----------------------------------------------------

let SEQ = 0;
const fid = () => "f" + SEQ++;

function makeField(o = {}) {
  return {
    id: fid(),
    name: "col",
    type: "INTEGER",
    size: "",
    notNull: false,
    primary: false,
    unique: false,
    increment: false,
    default: "",
    check: "",
    comment: "",
    values: [],
    isArray: false,
    ...o,
  };
}

function makeTable(o = {}) {
  return {
    id: "t" + SEQ++,
    name: "t",
    comment: "",
    color: "#175e7a",
    indices: [],
    uniqueConstraints: [],
    inherits: [],
    fields: [],
    ...o,
  };
}

function makeDiagram(o = {}) {
  return {
    database: DB.POSTGRES,
    tables: [],
    references: [],
    enums: [],
    types: [],
    ...o,
  };
}

