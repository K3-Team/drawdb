describe("toPostgres round-trip", () => {
  it("preserves fields, flags, comments, unique constraint, index, enum, type and FK", () => {
    const uid = fid();
    const aid = fid();
    const diagram = makeDiagram({
      tables: [
        makeTable({
          id: "users",
          name: "users",
          comment: "the users",
          indices: [{ id: 0, name: "idx_email", unique: false, fields: ["email"] }],
          fields: [
            makeField({ id: uid, name: "id", type: "INTEGER", notNull: true, primary: true, increment: true }),
            makeField({ name: "email", type: "VARCHAR", size: 255, notNull: true, unique: true, comment: "the email" }),
            makeField({ name: "tags", type: "TEXT", isArray: true }),
            makeField({ name: "status", type: "VARCHAR", size: 20, default: "active" }),
            makeField({ name: "active", type: "BOOLEAN", default: "true" }),
          ],
        }),
        makeTable({
          id: "posts",
          name: "posts",
          uniqueConstraints: [{ id: 0, name: "uq_slug", fields: ["slug"] }],
          fields: [
            makeField({ name: "id", type: "INTEGER", primary: true, increment: true }),
            makeField({ id: aid, name: "author_id", type: "INTEGER" }),
            makeField({ name: "slug", type: "VARCHAR", size: 100 }),
          ],
        }),
      ],
      references: [
        {
          id: "r1",
          name: "fk_posts_author",
          startTableId: "posts",
          endTableId: "users",
          startFieldId: aid,
          endFieldId: uid,
          fields: [{ startFieldId: aid, endFieldId: uid }],
          updateConstraint: "Cascade",
          deleteConstraint: "Restrict",
        },
      ],
      enums: [{ name: "mood", values: ["happy", "sad"] }],
      // no type comment: COMMENT ON TYPE is valid PG but not re-parseable, so it
      // would break the round trip (documented in the design doc).
      types: [{ name: "addr", comment: "", fields: [{ name: "street", type: "TEXT" }, { name: "zip", type: "INTEGER" }] }],
    });

    const { imported } = roundTrip(diagram);

    const users = imported.tables.find((t) => t.name === "users");
    const f = (t, n) => t.fields.find((x) => x.name === n);
    expect(f(users, "id").increment).toBe(true);
    expect(f(users, "id").primary).toBe(true);
    expect(f(users, "email").unique).toBe(true);
    expect(f(users, "email").comment).toBe("the email");
    expect(f(users, "tags").isArray).toBe(true);
    expect(f(users, "status").default).toBe("active");
    expect(users.comment).toBe("the users");
    expect(users.indices.map((i) => i.name)).toContain("idx_email");

    const posts = imported.tables.find((t) => t.name === "posts");
    expect(posts.uniqueConstraints[0].name).toBe("uq_slug");

    expect(imported.relationships).toHaveLength(1);
    const r = imported.relationships[0];
    expect(r.startTableId).toBe(posts.id);
    expect(r.endTableId).toBe(users.id);
    expect(r.updateConstraint).toBe("Cascade");
    expect(r.deleteConstraint).toBe("Restrict");

    expect(imported.enums).toEqual([{ name: "mood", values: ["happy", "sad"] }]);
    expect(imported.types[0].name).toBe("addr");
    expect(imported.types[0].fields.map((x) => x.name)).toEqual(["street", "zip"]);
  });
});

